/**
 * `npm run assets:licenses` — writes `assets/LICENSES.md` from `assets/manifest.json`: every asset with its source page,
 * author, licence, the page that states the licence and the day it was checked. `--check` only verifies that the file is
 * up to date (used by the tests and CI).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { ManifestSchema, manifestProblems } from '../src/assets/manifest';

export function licensesMarkdown(manifestText: string): string {
  const m = ManifestSchema.parse(JSON.parse(manifestText));
  const problems = manifestProblems(m);
  if (problems.length) throw new Error(problems.join('\n'));
  const rows = m.assets.map(
    (a) =>
      `| ${a.id} | ${a.kind} | ${a.name.replace(/\|/g, '/')} | ${a.author.replace(/\|/g, '/')} | [${a.source.provider}](${a.source.pageUrl}) | ${a.license} ([stated here](${a.licenseUrl})) | ${a.downloaded} |`,
  );
  return [
    '# Asset licences',
    '',
    'Generated by `npm run assets:licenses` from `assets/manifest.json`. Do not edit by hand.',
    '',
    'Every asset below is **CC0 1.0 (public domain dedication)**: free to use, change and redistribute, with no attribution',
    'required (the authors are credited anyway). An asset whose licence is not on the allow-list in `src/assets/manifest.ts`',
    'cannot be added: the downloader and the tests refuse it. The binaries are not kept in git; `npm run assets:download`',
    'fetches them from the pages listed here and checks the pinned SHA-256 of each download.',
    '',
    `Sources: Poly Haven (<https://polyhaven.com/license>), ambientCG (<https://docs.ambientcg.com/license/>), Kenney (<https://kenney.nl/support>: all Kenney assets are CC0).`,
    '',
    `${m.assets.length} assets (${m.assets.filter((a) => a.kind === 'model').length} models, ${m.assets.filter((a) => a.kind === 'texture').length} texture sets, ${m.assets.filter((a) => a.kind === 'hdri').length} HDRIs).`,
    '',
    '| Id | Kind | Name | Author | Source | Licence | Checked / downloaded |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('assets-licenses.ts')) {
  const root = process.env.ASSETS_DIR ?? 'assets';
  const text = licensesMarkdown(readFileSync(`${root}/manifest.json`, 'utf8'));
  const file = `${root}/LICENSES.md`;
  if (process.argv.includes('--check')) {
    const same = existsSync(file) && readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === text;
    console.log(
      same
        ? 'LICENSES.md is up to date'
        : 'LICENSES.md is out of date: run npm run assets:licenses',
    );
    process.exit(same ? 0 : 1);
  }
  writeFileSync(file, text, 'utf8');
  console.log(`wrote ${file}`);
}
