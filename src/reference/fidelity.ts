import type { BuildResult } from './build';
import { type DesignSpec, type ReferenceSpec, polygonOf } from './spec';

/** Width × depth of the bounding box of a room or zone, in spec units. */
export function sizeOf(s: {
  rect?: readonly [number, number, number, number];
  polygon?: [number, number][];
}): [number, number] {
  const pts = polygonOf(s);
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return [Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)];
}

const fmt = (units: 'ft' | 'm', v: number) =>
  units === 'ft' ? `${v.toFixed(1)}'` : `${v.toFixed(2)} m`;
const fmtSize = (units: 'ft' | 'm', s?: readonly [number, number]) =>
  s ? `${fmt(units, s[0])} × ${fmt(units, s[1])}` : '—';

const INCH = (units: 'ft' | 'm') => (units === 'ft' ? 1 / 12 : 0.0254);

interface Element {
  id: string;
  name: string;
  kind: string;
  labelSize?: readonly [number, number];
  note?: string;
}

const elementsOf = (d: DesignSpec): Element[] => [
  ...d.rooms.map((r) => ({
    id: r.id,
    name: r.name,
    kind: `room (${r.type})`,
    labelSize: r.labelSize,
    note: r.note,
  })),
  ...d.zones.map((z) => ({
    id: z.id,
    name: z.name,
    kind: `zone (${z.type})`,
    labelSize: z.labelSize,
    note: z.note,
  })),
];

const geometryOf = (d: DesignSpec, id: string) => {
  const r = d.rooms.find((x) => x.id === id) ?? d.zones.find((x) => x.id === id);
  return r ? sizeOf(r) : undefined;
};

/** Total deviation of a size from a label, in the smaller of the two orientations (a 14 × 12 room may be drawn 12 × 14). */
const deviation = (a: readonly [number, number], b: readonly [number, number]) =>
  Math.min(
    Math.max(Math.abs(a[0] - b[0]), Math.abs(a[1] - b[1])),
    Math.max(Math.abs(a[0] - b[1]), Math.abs(a[1] - b[0])),
  );

/** The fidelity report (Markdown): every element of the picture against its label, the picture and the model. */
export function fidelityMarkdown(
  spec: ReferenceSpec,
  result: BuildResult,
  generatedBy = 'npm run reference:build',
): string {
  const u = spec.units;
  const [A, ...others] = spec.designs;
  const pictured = others.length ? others[others.length - 1]! : undefined;
  const out: string[] = [];
  out.push(`# Fidelity report — ${spec.name}`);
  out.push('');
  out.push(
    `Generated by \`${generatedBy}\` from the spec. Do not edit by hand: change the spec and rebuild.`,
  );
  out.push('');
  out.push(
    `- **Option ${A!.letter ?? A!.id} "${A!.name}"**: ${A!.description ?? 'every labelled room has exactly its labelled size.'}`,
  );
  if (pictured)
    out.push(
      `- **Option ${pictured.letter ?? pictured.id} "${pictured.name}"**: ${pictured.description ?? 'proportions measured from the rectified picture.'}`,
    );
  out.push(
    `- Units: ${u === 'ft' ? 'feet' : 'metres'}. "Pictured" is the size measured in the rectified picture (the last option).`,
  );
  out.push('');

  // ── Rooms and zones ──
  const ids = new Map<string, Element>();
  for (const d of spec.designs) for (const e of elementsOf(d)) if (!ids.has(e.id)) ids.set(e.id, e);
  out.push('## Rooms and outdoor areas');
  out.push('');
  const head = [
    'Element',
    'Kind',
    'Labelled',
    'Pictured',
    ...spec.designs.map((d) => `Option ${d.letter ?? d.id}`),
    'A vs label',
    'Notes',
  ];
  out.push(`| ${head.join(' | ')} |`);
  out.push(`|${head.map(() => ' --- ').join('|')}|`);
  let labelled = 0;
  let within = 0;
  for (const [id, e] of ids) {
    const sizes = spec.designs.map((d) => geometryOf(d, id));
    const label =
      spec.designs.map((d) => elementsOf(d).find((x) => x.id === id)?.labelSize).find(Boolean) ??
      e.labelSize;
    const pic = pictured ? geometryOf(pictured, id) : undefined;
    let dev = '—';
    if (label && sizes[0]) {
      labelled++;
      const d = deviation(sizes[0], label);
      if (d <= INCH(u) + 1e-9) within++;
      dev = u === 'ft' ? `${(d * 12).toFixed(1)} in` : `${(d * 1000).toFixed(0)} mm`;
    }
    const note =
      spec.designs.map((d) => elementsOf(d).find((x) => x.id === id)?.note).find(Boolean) ?? '';
    const missing = spec.designs
      .map((d, i) => (sizes[i] ? '' : `not in option ${d.letter ?? d.id}`))
      .filter(Boolean)
      .join('; ');
    out.push(
      `| ${[e.name, e.kind, fmtSize(u, label), fmtSize(u, pic), ...sizes.map((s) => fmtSize(u, s)), dev, [note, missing].filter(Boolean).join('; ')].join(' | ')} |`,
    );
  }
  out.push('');
  out.push(
    `**Option ${A!.letter ?? A!.id} labelled sizes within 1 inch: ${within} of ${labelled}.**`,
  );
  out.push('');

  // ── Inventory ──
  const inventory = new Map<string, { catalog: Set<string>; inDesign: boolean[]; note: string }>();
  spec.designs.forEach((d, di) => {
    const add = (inv: string | undefined, catalog: string, note?: string) => {
      if (!inv) return;
      const row = inventory.get(inv) ?? {
        catalog: new Set<string>(),
        inDesign: spec.designs.map(() => false),
        note: '',
      };
      row.catalog.add(catalog);
      row.inDesign[di] = true;
      if (note && !row.note) row.note = note;
      inventory.set(inv, row);
    };
    for (const i of d.items) add(i.inventory, i.catalog, i.note);
    for (const l of d.lines) add(l.inventory, l.catalog, l.note);
  });
  if (inventory.size) {
    out.push('## Inventory of the picture (furniture, planting, features)');
    out.push('');
    const h2 = [
      'Element',
      ...spec.designs.map((d) => `Option ${d.letter ?? d.id}`),
      'Catalogue item(s)',
      'Notes',
    ];
    out.push(`| ${h2.join(' | ')} |`);
    out.push(`|${h2.map(() => ' --- ').join('|')}|`);
    for (const [name, row] of inventory)
      out.push(
        `| ${[name, ...row.inDesign.map((b) => (b ? '✓' : '—')), [...row.catalog].join(', '), row.note].join(' | ')} |`,
      );
    out.push('');
  }

  // ── Build report ──
  out.push('## Build report');
  out.push('');
  for (const r of result.report.designs) {
    out.push(`### Option ${spec.designs.find((d) => d.id === r.id)?.letter ?? r.id} — ${r.name}`);
    out.push('');
    out.push(
      `- ${r.rooms} rooms, ${r.walls} walls, ${r.openings} doors/windows, ${r.items} items, ${r.zones} outdoor zones`,
    );
    out.push(
      `- Overlapping rooms: ${r.overlaps.length ? r.overlaps.map((o) => `${o.a} / ${o.b} (${o.area.toFixed(2)} m²)`).join('; ') : 'none'}`,
    );
    out.push(
      `- Gaps inside the built area: ${r.gaps.length ? r.gaps.map((g) => `${g.area.toFixed(2)} m² (${g.level})`).join('; ') : 'none'}`,
    );
    out.push(`- Unreachable rooms: ${r.unreachable.length ? r.unreachable.join('; ') : 'none'}`);
    if (r.warnings.length) {
      out.push('- Things that could not be placed exactly as asked:');
      for (const w of r.warnings) out.push(`  - ${w}`);
    }
    out.push('');
  }
  return out.join('\n');
}
